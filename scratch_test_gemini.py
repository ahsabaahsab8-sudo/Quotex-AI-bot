async def test_gemini_model(model_name: str, api_key: str, prompt: str):
    print(f"\n--- Testing Gemini Model: {model_name} ---")
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model_name}:generateContent?key={api_key}"
    payload = {
        "contents": [
            {
                "parts": [
                    {
                        "text": prompt
                    }
                ]
            }
        ],
        "generationConfig": {
            "responseMimeType": "application/json"
        }
    }
    headers = {
        "Content-Type": "application/json"
    }

    try:
        response = requests.post(url, json=payload, headers=headers, timeout=60.0)
        print(f"HTTP Status Code: {response.status_code}")
        if response.status_code == 200:
            res_json = response.json()
            try:
                candidate_text = res_json['candidates'][0]['content']['parts'][0]['text']
                print("Response received successfully:")
                print(candidate_text)
            except Exception as parse_err:
                print(f"Failed to parse text from Gemini response: {parse_err}")
                print(json.dumps(res_json, indent=2))
        else:
            print("Error response text:")
            print(response.text)
    except Exception as e:
        print(f"API Request Exception: {e}")

async def list_available_models(api_key: str):
    print("\n--- Listing Available Models for this API Key ---")
    url = f"https://generativelanguage.googleapis.com/v1beta/models?key={api_key}"
    try:
        response = requests.get(url, timeout=30.0)
        if response.status_code == 200:
            res = response.json()
            models = [m['name'].replace('models/', '') for m in res.get('models', [])]
            print(f"Available Models: {models}")
        else:
            print(f"Failed to list models (HTTP {response.status_code}): {response.text}")
    except Exception as e:
        print(f"Failed to list models exception: {e}")

