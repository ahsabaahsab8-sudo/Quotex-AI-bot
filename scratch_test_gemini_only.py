async def main():
    load_dotenv()
    gemini_key = os.getenv("GEMINI_API_KEY")
    if not gemini_key:
        print("Error: GEMINI_API_KEY is not configured in .env file.")
        return

    if len(sys.argv) < 3:
        print("Usage: python scratch_test_gemini_only.py <token> <payout>")
        return

    token = sys.argv[1]
    payout = int(sys.argv[2])

    print(f"\n==========================================")
    print(f"Starting Gemini 3.5 Flash Scan for: {token}")
    print(f"==========================================")

    # 1. Connect to Quotex and fetch live indicator data
    print("Connecting to Quotex and fetching telemetry data...")
    client = await get_quotex_connection()
    try:
        tech_data = await fetch_and_process_indicators(client, token, payout=payout)
        if not tech_data:
            print("Failed to fetch indicators/candles or pair has extremely low volatility.")
            return
        if tech_data == "LOW_VOLATILITY":
            print("Warning: Pair flagged as LOW_VOLATILITY, continuing test anyway...")
            
        print("\nSuccessfully fetched indicators and candle history!")
        print(f"Current price: {tech_data['summary']['current_price']}")
        print(f"1m RSI: {tech_data['summary']['metrics_1m']['rsi']:.2f}")
        print(f"1m Trend: {tech_data['summary']['metrics_1m']['trend']}")
        print(f"Payout Percentage: {tech_data['summary']['payout_percentage']}%")

        # 2. Run Query on Gemini 3.5 Flash Model Only
        print("\n[1/1] Querying Gemini 3.5 Flash via Google API...")
        gemini_result = await query_gemini_3_5_flash(tech_data, gemini_key)

        # 3. Print Results
        print("\n==========================================")
        print("          GEMINI 3.5 FLASH RESULT         ")
        print("==========================================\n")
        
        if gemini_result:
            print(f"Asset/Token: {gemini_result.get('token')}")
            print(f"Direction  : {gemini_result.get('direction')}")
            print(f"Confidence : {gemini_result.get('confidence')}%")
            print(f"Martingale : {gemini_result.get('martingale_recommendation')}")
            print("\nChain of Thought Reasoning:")
            cot = gemini_result.get('chain_of_thought_reasoning', {})
            for step, desc in cot.items():
                print(f" - {step}: {desc}")
            print(f"\nFinal Reason: {gemini_result.get('reason')}")
        else:
            print("FAILED to get response from Gemini 3.5 Flash")
            
        print("\n==========================================")
        
    finally:
        await client.close()

if __name__ == "__main__":
    asyncio.run(main())
